"""ESG scores for a company (best-effort, DB-cached).

Design note: Yahoo Finance deprecated its free Sustainalytics ESG feed, so
``yfinance(...).sustainability`` now 404s for every ticker (``esgPopulated:
False``). This module still attempts the pull — so numeric E/S/G scores populate
automatically if the user's yfinance version/environment can reach a working feed
— but returns ``None`` cleanly when the feed is unavailable. The ESG *section*
then delivers its value through the AI qualitative assessment on the frontend
(the "+ AI narrative" half of the chosen approach), which needs no numeric feed.

When numeric scores ARE available they are cached in the ``esg_scores`` table so
repeat page loads are instant/offline.
"""

from __future__ import annotations

import json
import logging
import sqlite3
from typing import Any, Optional

log = logging.getLogger("esg")

# Sustainalytics fields we surface when the feed returns them.
_ESG_FIELDS = (
    "totalEsg", "environmentScore", "socialScore", "governanceScore",
    "esgPerformance", "percentile", "highestControversy", "ratingYear", "ratingMonth",
)


def _ensure_table(conn: sqlite3.Connection) -> None:
    conn.execute(
        """CREATE TABLE IF NOT EXISTS esg_scores (
               ticker TEXT PRIMARY KEY, scores_json TEXT, updated TEXT)"""
    )


def _fetch_from_yfinance(ticker: str) -> Optional[dict[str, Any]]:
    """Attempt the (currently deprecated) Yahoo sustainability pull. Returns a
    scores dict, or None when the feed is unavailable/empty."""
    try:
        import yfinance as yf  # imported lazily; heavy
    except Exception:  # noqa: BLE001
        return None
    try:
        sust = yf.Ticker(ticker).sustainability
    except Exception:  # noqa: BLE001 — 404 / network / feed removed
        return None
    if sust is None or getattr(sust, "empty", True):
        return None
    try:
        col = sust.iloc[:, 0].to_dict()
    except Exception:  # noqa: BLE001
        return None
    scores = {k: col[k] for k in _ESG_FIELDS if k in col and col[k] is not None}
    return scores or None


def get_esg(conn: sqlite3.Connection, ticker: str, *, force: bool = False) -> Optional[dict[str, Any]]:
    """DB-cached ESG scores for one ticker. Returns None when no numeric feed is
    available (the AI qualitative ESG read is then the section's content)."""
    _ensure_table(conn)
    ticker = ticker.upper()
    if not force:
        row = conn.execute(
            "SELECT scores_json FROM esg_scores WHERE ticker = ?", (ticker,)
        ).fetchone()
        if row is not None and row[0]:
            try:
                return json.loads(row[0])
            except (ValueError, TypeError):
                pass
    scores = _fetch_from_yfinance(ticker)
    if scores is None:
        return None
    conn.execute(
        "INSERT OR REPLACE INTO esg_scores (ticker, scores_json, updated) "
        "VALUES (?, ?, datetime('now'))",
        (ticker, json.dumps(scores)),
    )
    conn.commit()
    return scores


def read_cached_esg(conn: sqlite3.Connection, ticker: str) -> Optional[dict[str, Any]]:
    """Cache-only read (no network) — used on the request path so a dead feed
    never adds page-load latency. Warm-up jobs call get_esg to populate."""
    _ensure_table(conn)
    row = conn.execute(
        "SELECT scores_json FROM esg_scores WHERE ticker = ?", (ticker.upper(),)
    ).fetchone()
    if row is not None and row[0]:
        try:
            return json.loads(row[0])
        except (ValueError, TypeError):
            return None
    return None


def build_esg_block(conn: sqlite3.Connection, ticker: str, *, allow_fetch: bool = False) -> dict[str, Any]:
    """The ESG payload for the API. Always returns a block (so the frontend can
    render the AI qualitative section); ``scores`` is None when no numeric feed
    is available. ``allow_fetch=False`` (default) reads the cache only — the
    request path must not block on the (deprecated) Yahoo feed."""
    scores: Optional[dict[str, Any]] = None
    try:
        scores = get_esg(conn, ticker) if allow_fetch else read_cached_esg(conn, ticker)
    except Exception as exc:  # noqa: BLE001
        log.warning("esg fetch failed for %s: %s", ticker, exc)
    return {
        "scores": scores,
        "hasNumericScores": scores is not None,
        "source": "sustainalytics_yfinance" if scores is not None else "ai_qualitative",
        "note": (
            "Numeric Sustainalytics ESG scores from Yahoo Finance."
            if scores is not None else
            "Yahoo's free ESG data feed is currently unavailable, so this ESG "
            "assessment is generated by AI from the company's filings and public "
            "record rather than a numeric third-party score."
        ),
    }
