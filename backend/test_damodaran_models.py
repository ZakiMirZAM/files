def test_fcff_growth_uncapped_measures_what_legacy_clamped():
    # A firm reinvesting 120% of NOPAT: legacy clamps to 90%, the engine
    # measures it (Damodaran's own examples exceed 100%).
    rows = [_row(2023, 900.0, 100.0, capex=-160.0, dep=40.0, d_nwc=0.0),
            _row(2024, 1000.0, 100.0, capex=-160.0, dep=40.0, d_nwc=0.0)]
    nopat = vi.nopat_for_row(rows[-1])
    raw_rate = (160.0 - 40.0) / nopat
    assert raw_rate > 1.0
    legacy = vg.fcff_growth(rows, roic=0.15, legacy_caps=True)
    engine = vg.fcff_growth(rows, roic=0.15)
    assert legacy["reinvestmentRate"] == pytest.approx(0.90)
    assert engine["reinvestmentRate"] == pytest.approx(raw_rate, abs=0.001)
    assert engine["growth"] > legacy["growth"]


