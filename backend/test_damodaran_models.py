def _payer_with_buybacks():
    rows, rev, op = [], 900.0, 150.0
    for y in range(2017, 2026):
        ni = op * 0.75
        rows.append(_row(
            y, rev, op, equity=1200.0, debt=400.0, cash=100.0,
            capex=-80.0, dep=60.0,
            **{
                "Weighted Average Shs Out Dil": 100.0,
                "Dividends Paid": -(ni * 0.4),
                "Common Stock Repurchased": -(ni * 0.2),
                "Total Assets": 2400.0,
            },
        ))
        rev *= 1.05
        op *= 1.05
    return rows


def test_damodaran_ddm_uses_augmented_payout_and_stage_variants(monkeypatch):
    monkeypatch.delenv("VALUATION_ENGINE", raising=False)
    ddm = ia._dividend_discount_model(_payer_with_buybacks(), beta=1.0,
                                      rf=0.04, erp=0.045, price=50.0)
    assert ddm.get("applicable")
    assert ddm["buybacksIncluded"] is True
    # Payout counts buybacks: 40% dividends + 20% repurchases = 60%.
    assert ddm["payout"] == pytest.approx(0.60, abs=0.01)
    assert set(ddm["stageVariants"].keys()) == {"1", "2", "3"}
    rec = ddm["stageVariants"][str(ddm["recommendedStages"])]
    assert rec["applicable"]
    assert ddm["intrinsicPerShare"] == rec["intrinsicPerShare"]
    # Stable discipline: terminal growth capped at rf, terminal payout 1 − g/ROE.
    assert ddm["growthTerminal"] <= 0.04 + 1e-9
    assert 0.0 <= ddm["terminalPayout"] <= 1.0


