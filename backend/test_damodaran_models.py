# Coca-Cola, May 2011 (Ch. 13.3): aggregate 2006-2010 augmented payout 63.60%
# vs conventional 49.15%; at ROE 25% the augmented growth is 9.1%.

def test_coca_cola_augmented_payout_growth():
    rows = []
    for i in range(5):
        ni = 10_000.0
        rows.append(_row(2006 + i, 30_000.0, ni / 0.75,
                         **{"Net Income": ni,
                            "Dividends Paid": -ni * 0.4915,
                            "Common Stock Repurchased": -ni * (0.6360 - 0.4915)}))
    out = vg.ddm_growth(rows, roe_override=0.25)
    assert out is not None
    assert out["augmentedPayout"] == pytest.approx(0.6360, abs=0.0005)
    assert out["conventionalPayout"] == pytest.approx(0.4915, abs=0.0005)
    assert out["buybacksIncluded"] is True
    assert out["growth"] == pytest.approx(0.25 * (1 - 0.6360), abs=0.0005)   # 9.1%


