def test_negative_margin_firm_routes_to_the_revenue_driven_path(monkeypatch):
    # A loss-making firm with NEGATIVE book equity can show a spuriously
    # "positive" ROIC (negative NOPAT over negative capital). The SELECTOR owns
    # the track decision: negative margins send it down the revenue-driven
    # n-stage path, never the earnings engine (the review's critical case).
    monkeypatch.delenv("VALUATION_ENGINE", raising=False)
    rows = []
    rev = 1000.0
    for y in range(2019, 2026):
        rows.append(_row(y, rev, -80.0, equity=-500.0, debt=100.0,
                         **{"Weighted Average Shs Out Dil": 100.0}))
        rev *= 1.25
    fc = ia.compute_forecast(rows, beta=1.2, rf=0.04, erp=0.045, price=20.0,
                             industry_norms={"salesToInvestedCapital": 2.0,
                                             "operatingMargin": 0.12,
                                             "revenueGrowth": 0.10})
    assert fc is not None
    if fc.get("applicable") is False:
        # Acceptable only if the revenue path itself is unsolvable — but the
        # industry norms provided make it solvable, so this must not happen.
        raise AssertionError(f"expected a valuation, got: {fc.get('reason')}")
    sel = fc["valuationSelection"]
    assert sel["track"] == "nstage"
    assert fc["growthReconciliation"]["reinvestmentMethod"] == "salesToCapital"
    # 1/2-stage are structurally invalid for a loss-maker; 3 carries the value.
    assert not sel["stageVariants"]["1"]["applicable"]
    assert not sel["stageVariants"]["2"]["applicable"]
    assert sel["stageVariants"]["3"]["applicable"]


