# Volkswagen, May 2011 (Ch. 14.1, Illustration 14.2): 2010 capex 11,462,
# depreciation 10,089, ΔNoncash WC +423 ⇒ gross reinvestment 1,796m; with
# ~40% of reinvestment funded by new debt the EQUITY reinvestment rate is
# 1,796 × (1 − .40) / 5,279 = 20.41%; at noncash ROE 10% ⇒ g 2.04%.

def test_volkswagen_equity_reinvestment_growth():
    gross = 11_462.0 - 10_089.0 + 423.0            # 1,796m
    prev = _row(2009, 100_000.0, 9_000.0,
                **{"Net Income": 5_000.0, "Total Debt": 40_000.0})
    curr = _row(2010, 105_000.0, 9_500.0,
                **{"Net Income": 5_279.0,
                   "Capital Expenditure": -11_462.0,
                   "Depreciation and Amortization Cashflow": 10_089.0,
                   # ΔNoncash WC investment of +423 arrives as a cash-flow
                   # value of −423 (cash used by working capital).
                   "Change In Working Capital": -423.0,
                   # 40% of reinvestment funded by net new debt (VW's book
                   # debt ratio), so equity carries the remaining 60%.
                   "Total Debt": 40_000.0 + gross * 0.40})
    err = vi.equity_reinvestment_rate([prev, curr], window=1)
    assert err is not None
    assert err["netDebtSource"] == "balanceSheetDelta"
    assert err["value"] == pytest.approx(0.2041, abs=0.0005)
    out = vg.fcfe_growth([prev, curr], window=1, roe_override=0.10)
    assert out["growth"] == pytest.approx(0.0204, abs=0.0005)


def test_equity_reinvestment_short_form_when_debt_delta_is_unavailable():
    # A single year with no prior row: the Ch. 14 short form applies with the
    # book debt-to-capital ratio, and the provenance says so.
    gross = 11_462.0 - 10_089.0 + 423.0
    only = _row(2010, 105_000.0, 9_500.0,
                **{"Net Income": 5_279.0,
                   "Capital Expenditure": -11_462.0,
                   "Depreciation and Amortization Cashflow": 10_089.0,
                   "Change In Working Capital": -423.0,
                   "Total Debt": 40_000.0,
                   "Total Stockholders Equity": 60_000.0})   # D/C = 40%
    err = vi.equity_reinvestment_rate([only], window=1)
    assert err is not None
    assert err["netDebtSource"] == "shortFormBookDC"
    assert err["value"] == pytest.approx(gross * 0.60 / 5_279.0, abs=0.0005)


