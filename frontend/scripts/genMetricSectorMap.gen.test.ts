// The metric-sector dataset generator.
//
// It runs as a vitest test rather than a plain node script for one reason: the
// parser is TypeScript and reads the definition markdown through Vite's raw
// glob, so running it under vitest keeps EXACTLY ONE parser implementation
// shared by the generator, the unit tests and the sync test. A second copy in
// plain JavaScript is how a generated dataset drifts from the files it claims
// to mirror.
//
// It is gated on GEN_METRIC_MAP so a normal `npm test` never writes files.
// vitest.gen.config.ts sets that variable, and package.json wires it up:
//
//     npm run gen:metric-map
//
// Outputs:
//   src/lib/generated/metricSectorMap.ts       the typed dataset
//   src/lib/generated/metricSectorMapSlim.ts   the four fields the block reads
//   tmp/definition-gaps.md                     the gap report for the owner

import { describe, expect, it } from "vitest";
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import { definitionSources } from "../src/lib/definitionSources";
import {
  parseDefinitionFile,
  sectorsWithoutMechanism,
  type MetricSectorEntry,
  type MetricSectorMap,
} from "../src/lib/definitionTables";
import { ODD_TOKENS } from "../src/lib/gicsSectorMap";
import { slimMetricSectorMap } from "../src/lib/metricSectorSlim";
import { SECTORS } from "../src/lib/sectorRotation";

const HERE = dirname(fileURLToPath(import.meta.url));
const FRONTEND = join(HERE, "..");
const OUT_TS = join(FRONTEND, "src", "lib", "generated", "metricSectorMap.ts");
const OUT_SLIM = join(FRONTEND, "src", "lib", "generated", "metricSectorMapSlim.ts");
const OUT_GAPS = join(FRONTEND, "tmp", "definition-gaps.md");

/** U+2014 EM DASH, built at runtime so no literal em dash lives in source. */
const EM_DASH = String.fromCharCode(0x2014);

const HEADER = `// Generated by scripts/genMetricSectorMap.mjs. Do not edit.
//
// That entry point hands the work to scripts/genMetricSectorMap.gen.test.ts,
// which runs under vitest so the generator and the tests share one parser.
//
// Every cell below is the owner's own text from src/content/economic and
// src/content/credit, trimmed and otherwise word for word. Regenerate with
// \`npm run gen:metric-map\` after editing any definition file; the sync test in
// src/lib/metricSectorMap.sync.test.ts fails while this file is stale.

import type { MetricSectorMap } from "../definitionTables";

export const METRIC_SECTOR_MAP: MetricSectorMap = `;

const SLIM_HEADER = `// Generated by scripts/genMetricSectorMap.mjs. Do not edit.
//
// The four fields the cross-stage data block reads out of METRIC_SECTOR_MAP:
// each reading's label, the three sector lists under it, and the first sentence
// of each Part 4 mechanism. See lib/metricSectorSlim.ts for why this second
// artifact exists; the sync test in src/lib/metricSectorMap.sync.test.ts fails
// while it is stale.

import type { SlimMetricSectorMap } from "../metricSectorSlim";

export const METRIC_SECTOR_SLIM: SlimMetricSectorMap = `;

/** Build the dataset from the markdown. Pure, so the sync test reuses it. */
export function buildMetricSectorMap(): MetricSectorMap {
  const map: MetricSectorMap = { economic: {}, credit: {} };
  for (const src of definitionSources()) {
    const parsed = parseDefinitionFile(src.markdown, src.path);
    const entry: MetricSectorEntry = parsed.conforming
      ? {
          surface: src.surface,
          number: src.number,
          title: parsed.title,
          file: src.file,
          conforming: true,
          problems: [],
          part3: parsed.part3,
          part4: parsed.part4,
          part5: parsed.part5,
        }
      : {
          surface: src.surface,
          number: src.number,
          title: parsed.title,
          file: src.file,
          conforming: false,
          problems: parsed.problems,
          part3: [],
          part4: [],
          part5: [],
        };
    map[src.surface][String(src.number)] = entry;
  }
  return map;
}

function gapReport(map: MetricSectorMap): string {
  const lines: string[] = [];
  lines.push("# Definition table gaps");
  lines.push("");
  lines.push(
    "Generated by `npm run gen:metric-map`. Everything here is a gap in the source " +
      "markdown under `frontend/src/content`, not a code defect. Nothing in the app " +
      "invents a value for any of it.",
  );
  lines.push("");

  lines.push("## Files that do not conform");
  lines.push("");
  const bad = [...Object.values(map.economic), ...Object.values(map.credit)].filter(
    (e) => !e.conforming,
  );
  if (bad.length === 0) {
    lines.push("None.");
  } else {
    lines.push("| Surface | Number | File | Problem |");
    lines.push("|---|---|---|---|");
    for (const e of bad) {
      for (const p of e.problems) {
        lines.push(`| ${e.surface} | ${e.number} | ${e.file} | ${p.replace(/\|/g, "\\|")} |`);
      }
    }
  }
  lines.push("");

  lines.push("## Sectors with no Part 4 mechanism row");
  lines.push("");
  lines.push("| Surface | Number | File | Sectors with no row written |");
  lines.push("|---|---|---|---|");
  let missingRows = 0;
  for (const e of [...Object.values(map.economic), ...Object.values(map.credit)]) {
    if (!e.conforming) continue;
    const missing = sectorsWithoutMechanism(
      { conforming: true, title: e.title, part3: e.part3, part4: e.part4, part5: e.part5 },
      SECTORS,
    );
    if (missing.length === 0) continue;
    missingRows += missing.length;
    lines.push(`| ${e.surface} | ${e.number} | ${e.file} | ${missing.join(", ")} |`);
  }
  if (missingRows === 0) lines.push("| | | | none |");
  lines.push("");
  lines.push(`Total sector cells with no mechanism row written: ${missingRows}.`);
  lines.push("");

  lines.push("## Odd tokens in use");
  lines.push("");
  lines.push(
    "Every token below is resolved by an explicit row in `lib/gicsSectorMap.ts`. " +
      "A token that is not listed there makes its file non-conforming.",
  );
  lines.push("");
  lines.push("| Token | Resolves to | Kind | Qualifier |");
  lines.push("|---|---|---|---|");
  for (const [token, resolved] of Object.entries(ODD_TOKENS)) {
    const to =
      resolved.sectors.length === SECTORS.length
        ? "all eleven"
        : resolved.sectors.join(", ") || "(no sector)";
    lines.push(`| ${token} | ${to} | ${resolved.kind} | ${resolved.qualifier ?? ""} |`);
  }
  lines.push("");
  return lines.join("\n");
}

describe("generate the metric sector dataset", () => {
  it.skipIf(!process.env.GEN_METRIC_MAP)(
    "writes the two generated datasets and tmp/definition-gaps.md",
    () => {
      const map = buildMetricSectorMap();
      const body = JSON.stringify(map, null, 2);
      const slim = JSON.stringify(slimMetricSectorMap(map), null, 2);

      // The owner's content is em-dash free today and the repo rule says it
      // stays that way. Fail loudly rather than write one into src/.
      expect(body.includes(EM_DASH), "a definition cell now carries an em dash").toBe(false);

      mkdirSync(dirname(OUT_TS), { recursive: true });
      writeFileSync(OUT_TS, `${HEADER}${body};\n`, "utf8");
      writeFileSync(OUT_SLIM, `${SLIM_HEADER}${slim};\n`, "utf8");

      mkdirSync(dirname(OUT_GAPS), { recursive: true });
      writeFileSync(OUT_GAPS, gapReport(map), "utf8");

      const all = [...Object.values(map.economic), ...Object.values(map.credit)];
      expect(all.length).toBeGreaterThan(80);
    },
  );
});
